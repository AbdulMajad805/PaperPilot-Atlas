
from pathlib import Path

from app.models.paper_analysis import PaperAnalysis, PaperReview


def generate_markdown_report(
    analysis: PaperAnalysis,
    review: PaperReview,
) -> str:
    """Generate a research-paper report from validated agent outputs."""

    def section(title: str, content: str, pages: list[int]) -> str:
        page_text = (
            f"**Source pages:** {', '.join(map(str, pages))}"
            if pages
            else "**Source pages:** Not specified"
        )

        return f"## {title}\n\n{content}\n\n{page_text}\n"

    def bullet_list(items: list[str]) -> str:
        if not items:
            return "- None reported\n"
        return "\n".join(f"- {item}" for item in items) + "\n"

    def review_items(items) -> str:
        if not items:
            return "- No verification items available.\n"

        result = []

        for item in items:
            pages = (
                ", ".join(map(str, item.page_references))
                if item.page_references
                else "Not specified"
            )

            result.append(
                f"### Claim\n{item.claim}\n\n"
                f"**Assessment:** {item.assessment}\n\n"
                f"**Evidence:** {item.evidence}\n\n"
                f"**Pages:** {pages}\n"
            )

        return "\n".join(result)

    metadata = analysis.metadata

    report = f"""# Research Paper Analysis Report

**Generated by:** PaperPilot AI

---

## Paper Information

- **Title:** {metadata.title}
- **Authors:** {', '.join(metadata.authors) or 'Not specified'}
- **Publication:** {metadata.publication}

---

## Executive Summary

{analysis.executive_summary}

---

{section("Research Problem", analysis.research_problem.content, analysis.research_problem.page_references)}
{section("Objectives", analysis.objectives.content, analysis.objectives.page_references)}
{section("Methodology", analysis.methodology.content, analysis.methodology.page_references)}
{section("Architecture", analysis.architecture.content, analysis.architecture.page_references)}
{section("Experimental Setup", analysis.experimental_setup.content, analysis.experimental_setup.page_references)}
{section("Datasets", analysis.datasets.content, analysis.datasets.page_references)}
{section("Results", analysis.results.content, analysis.results.page_references)}
{section("Contributions", analysis.contributions.content, analysis.contributions.page_references)}
{section("Limitations", analysis.limitations.content, analysis.limitations.page_references)}

---

# Reviewer Assessment

## Claim Verification

{review_items(review.verification_results)}

## Missing Information

{bullet_list(review.missing_information)}

## Unsupported Claims

{bullet_list(review.unsupported_claims)}

## Methodology Assessment

{review.methodology_assessment}

## Strengths

{bullet_list(review.strengths)}

## Reviewer-Identified Limitations

{bullet_list(review.limitations)}

## Research Insights

{bullet_list(review.research_insights)}

## Future Research Questions

{bullet_list(review.future_research_questions)}

## Overall Assessment

{review.overall_assessment}

---

*End of Report — PaperPilot AI*
"""

    return report.strip()


def save_markdown_report(
    report: str,
    output_path: str,
) -> Path:
    """Save the generated report and return its path."""

    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)

    path.write_text(report, encoding="utf-8")

    return path
